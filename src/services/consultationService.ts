/**
 * 021 — Consultation persistence service
 * Saves/updates consultation records in Supabase.
 */
import { supabase } from './supabaseClient';

export interface ConsultationRecord {
  id?: string;
  doctor_id: string;
  patient_name: string;
  dob: string;
  status: 'Upcoming' | 'Recording' | 'Draft' | 'Approved';
  time_slot?: string;
  duration_seconds?: number;
  audio_uri?: string | null;
  transcript?: string | null;
  transcript_language?: string;
  soap_note?: Record<string, any> | null;
  chief_complaint?: string | null;
  follow_up_date?: string | null;
  rx_notes?: string | null;
  patient_number?: number | null;
}

/** Create a new consultation row — returns the DB-generated id */
export async function createConsultation(data: ConsultationRecord): Promise<{ id: string, patientNumber: number | null } | null> {
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) throw new Error('Not authenticated');

  // 1. Ensure patient exists in the patients table, retrieve patient_number
  let patientId: string | null = null;
  let patientNumber: number | null = null;

  const { data: existingPatients, error: patientFetchError } = await supabase
    .from('patients')
    .select('id, patient_number')
    .eq('doctor_id', user.id)
    .ilike('name', data.patient_name)
    .eq('dob', data.dob)
    .limit(1);

  if (!patientFetchError && existingPatients && existingPatients.length > 0) {
    patientId = existingPatients[0].id;
    patientNumber = existingPatients[0].patient_number ?? null;
  } else {
    // Insert new patient — patient_number is auto-generated by SERIAL
    const { data: newPatient, error: patientInsertError } = await supabase
      .from('patients')
      .insert({
        doctor_id: user.id,
        name: data.patient_name,
        dob: data.dob
      })
      .select('id, patient_number')
      .single();

    if (!patientInsertError && newPatient) {
      patientId = newPatient.id;
      patientNumber = newPatient.patient_number ?? null;
    }
  }

  // 2. Insert the consultation with patient_number for easy display
  const { data: row, error } = await supabase
    .from('consultations')
    .insert({
      ...data,
      doctor_id: user.id,
      patient_id: patientId,
      patient_number: patientNumber,
    })
    .select('id, patient_number')
    .single();

  if (error) throw new Error(`DB insert error: ${error.message}`);
  if (!row) return null;
  return { id: row.id, patientNumber: row.patient_number };
}

/** Get the patient_number for a consultation (used after creation) */
export async function getPatientNumber(consultationId: string): Promise<number | null> {
  const { data, error } = await supabase
    .from('consultations')
    .select('patient_number')
    .eq('id', consultationId)
    .single();

  if (error || !data) return null;
  return data.patient_number ?? null;
}

/** Update an existing consultation (partial update) */
export async function updateConsultation(
  id: string,
  patch: Partial<ConsultationRecord>
): Promise<void> {
  const { error } = await supabase
    .from('consultations')
    .update(patch)
    .eq('id', id);

  if (error) throw new Error(`DB update error: ${error.message}`);
}

/** Delete a consultation by id */
export async function deleteConsultation(id: string): Promise<void> {
  const { error } = await supabase
    .from('consultations')
    .delete()
    .eq('id', id);

  if (error) throw new Error(`DB delete error: ${error.message}`);
}

/** Fetch all consultations for the logged-in doctor (today's + recent) */
export async function fetchConsultations(): Promise<ConsultationRecord[]> {
  const { data, error } = await supabase
    .from('consultations')
    .select('*')
    .order('created_at', { ascending: false })
    .limit(50);

  if (error) throw new Error(`DB fetch error: ${error.message}`);
  return data ?? [];
}
